pub const fn drive(serial: u32, requesting_id: u16) -> SlaveConfig {
    SlaveConfig {
        kind: SlaveKind::Drive,
        sii: &DRIVE_SII,
        serial,
        requesting_id,
        dc: true,
    }
}
pub const fn io() -> SlaveConfig {
    SlaveConfig {
        kind: SlaveKind::Io,
        sii: &IO_SII,
        serial: 0,
        requesting_id: 0,
        dc: false,
    }
}
pub const fn dual_axis_io() -> [SlaveConfig; 3] {
    [drive(1, 0x41), drive(2, 0x42), io()]
}

